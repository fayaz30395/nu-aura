import {chromium, newContext, watch, mkLog, FE, SS, sql, STATE} from './lib.mjs';
import fs from 'fs';
const T = 'NUAURA_TEST_E2E_' + Date.now().toString().slice(-6);
const out = {tag: T}; const b = await chromium.launch();
const c = await newContext(b, {role: 'recruiter'}); const p = await c.newPage(); const log = mkLog(); watch(p, log);
const api = []; p.on('response', async r => { const m = r.request().method(); if (m !== 'GET' && /\/recruitment\//.test(r.url())) api.push(`${m} ${r.status()} ${r.url().replace(/^https?:\/\/[^/]+/, '').replace(/[0-9a-f-]{36}/g, '{id}')}`); });
const step = async (n) => { await p.screenshot({path: `${SS}/NU-UI-004-${n}.png`}); };
// 1 job
await p.goto(`${FE}/recruitment/jobs`, {waitUntil: 'domcontentloaded', timeout: 120000}); await p.waitForLoadState('networkidle', {timeout: 30000}).catch(() => {});
await p.getByRole('button', {name: /create job opening/i}).first().click();
await p.locator('#job-form-code').fill(T + '_J'); await p.locator('#job-form-title').fill(T + '_Job');
await p.locator('#job-form-location').fill('Remote');
await p.locator('#job-form-department').selectOption({index: 1}).catch(async () => { await p.getByLabel('Department').selectOption({index: 1}); });
await p.locator('#job-form-status').selectOption({label: 'Open'}).catch(() => {});
await step('job-form');
const jr = p.waitForResponse(r => /job-openings$/.test(r.url()) && r.request().method() === 'POST', {timeout: 30000}).catch(() => null);
await p.getByRole('button', {name: 'Create Job', exact: true}).click();
const jresp = await jr; out.jobApi = jresp ? jresp.status() : 'no response';
if (jresp && jresp.status() >= 400) out.jobBody = (await jresp.text()).slice(0, 300);
await p.waitForTimeout(1500); await step('job-created');
out.jobUi = await p.getByText(T + '_Job').count();
out.jobDb = sql(`select job_code,job_title,status from job_openings where job_title='${T}_Job'`);
console.log('JOB', JSON.stringify(out)); if (!/^[0-9a-zA-Z_ ]+\|/.test(out.jobDb) && !out.jobDb) process.exit(2);
// 2 candidate
await p.goto(`${FE}/recruitment/candidates`, {waitUntil: 'domcontentloaded'}); await p.waitForLoadState('networkidle', {timeout: 30000}).catch(() => {});
await p.getByRole('button', {name: /add candidate/i}).first().click();
await p.locator('#candidate-code').fill(T + '_C');
await p.locator('#candidate-job-opening').selectOption({label: T + '_Job'}).catch(async e => { out.jobOpts = (await p.locator('#candidate-job-opening option').allInnerTexts()).slice(-5); throw e; });
await p.locator('#candidate-first-name').fill('NUAURA_TEST_E2E'); await p.locator('#candidate-last-name').fill('Cand' + T.slice(-4));
await p.locator('#candidate-email').fill(`nuaura_test_${T.slice(-6)}@example.invalid`);
await p.locator('#candidate-phone').fill('9000000000').catch(() => {});
await p.locator('#candidate-total-experience').fill('3'); await p.locator('#candidate-current-ctc').fill('500000'); await p.locator('#candidate-expected-ctc').fill('700000'); await p.locator('#candidate-notice-period').fill('30');
await p.locator('#candidate-status').selectOption('SELECTED');
await step('cand-form');
const cr = p.waitForResponse(r => /candidates$/.test(r.url()) && r.request().method() === 'POST', {timeout: 30000}).catch(() => null);
await p.locator('form button[type=submit]').click();
const cresp = await cr; out.candApi = cresp ? cresp.status() : 'no response';
if (cresp && cresp.status() >= 400) out.candBody = (await cresp.text()).slice(0, 300);
await p.waitForTimeout(1500); await step('cand-created');
out.candDb = sql(`select candidate_code,status,email from candidates where candidate_code='${T}_C'`);
// 3 offer
await p.getByPlaceholder(/search/i).first().fill(T + '_C').catch(() => {}); await p.waitForTimeout(1500);
const name = 'NUAURA_TEST_E2E Cand' + T.slice(-4);
await p.getByRole('button', {name: `More actions for ${name}`}).click();
await step('cand-menu');
await p.getByText('Generate Offer', {exact: true}).click();
await p.locator('#create-offer-salary').fill('750000'); await p.locator('#create-offer-joining-date').fill('2027-01-15');
await p.locator('#create-offer-position-title').fill(T + '_Pos').catch(() => {});
await step('offer-form');
const or = p.waitForResponse(r => /offers?/.test(r.url()) && r.request().method() === 'POST', {timeout: 30000}).catch(() => null);
await p.locator('form button[type=submit]').last().click();
const oresp = await or; out.offerApi = oresp ? `${oresp.status()} ${oresp.url().replace(/^https?:\/\/[^/]+/, '').replace(/[0-9a-f-]{36}/g, '{id}')}` : 'no response';
if (oresp && oresp.status() >= 400) out.offerBody = (await oresp.text()).slice(0, 300);
await p.waitForTimeout(2000); await step('offer-created');
out.offerDb = sql(`select status, offered_ctc, proposed_joining_date, offer_extended_date is not null, offered_designation from candidates where candidate_code='${T}_C'`);
out.api = api; out.log = log;
console.log(JSON.stringify(out, null, 1).slice(0, 4500)); fs.writeFileSync(STATE + '/j4.json', JSON.stringify(out));
await b.close();
